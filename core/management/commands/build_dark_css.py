"""
Write static/css/dark.css - the dark theme - from the compiled static/css/app.css.

    python manage.py build_dark_css

Run by build-css.ps1 / build-css.sh straight after Tailwind, so the two files
never drift apart (core/tests_templates.py fails if they do). Never edit
dark.css by hand.

How the theme is made
---------------------
The templates are written in Tailwind utilities for a light page. Rather than
give every template a `dark:` twin of every colour, the theme works on the
compiled stylesheet, in three ways, all scoped to html[data-theme="dark"]:

  * Neutral greys: the slate scale is redefined light-for-dark, so text,
    borders, dividers and hover fills follow wherever they are used. The few
    dark slate backgrounds - the translucent backdrops behind dialogs - are
    pinned to their original dark values so they stay backdrops.
  * White surfaces: bg-white becomes the card colour.
  * Every other colour (brand, status reds, ambers, greens, ...): its pale
    tints (backgrounds 50-200, borders 100-300) become translucent tints of
    the colour's middle shade, and its dark text shades (600-950) become the
    matching light shade. Filled buttons and badges - backgrounds 300 and
    above - keep their colour, so white text on them still reads.

The sidebar and the government band are already navy with white text and are
untouched by any of this.
"""

import re
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

SCOPE = 'html[data-theme="dark"]'

# The dark-mode slate scale: page, card and chip fills dark, text light.
SLATE = {
    "50": "oklch(16% .035 264)",     # page background
    "100": "oklch(26% .04 262)",     # chips, subtle fills
    "200": "oklch(33% .04 260)",     # borders
    "300": "oklch(42% .04 258)",
    "400": "oklch(57% .04 257)",     # icons, placeholders
    "500": "oklch(68% .035 256)",    # secondary text
    "600": "oklch(77% .025 254)",
    "700": "oklch(86% .018 253)",
    "800": "oklch(92% .012 255)",
    "900": "oklch(96.5% .007 248)",  # headings
    "950": "oklch(98.4% .003 248)",
}
SURFACE = "oklch(21% .04 265)"       # cards (bg-white)

TEXT_SHADE = {"600": "400", "700": "300", "800": "200", "900": "200", "950": "100"}
BG_TINT = {"50": 14, "100": 20, "200": 28}
BORDER_TINT = {"100": 30, "200": 38, "300": 48}

RULE = re.compile(r"([^{}]+)\{([^{}]*)\}")
COLOR_VAR = re.compile(r"var\(--color-([a-z]+)-(\d{2,3})\)")
SLATE_VALUE = re.compile(r"--color-slate-(\d+):([^;}]+)")
WHITE_ALPHA = re.compile(r"var\(--color-white\)\s*(\d+)%")


def convert(prop, value, original_slate):
    """The dark-theme value for one declaration, or None to leave it."""
    if prop == "background-color" and "var(--color-white)" in value:
        # Translucent white on the navy sidebar stays as it is.
        match = WHITE_ALPHA.search(value)
        if match and int(match.group(1)) < 50:
            return None
        return value.replace("var(--color-white)", "var(--lgmed-surface)")

    changed = False

    def swap(match):
        nonlocal changed
        hue, shade = match.group(1), match.group(2)
        if hue == "slate":
            # Dark slate backgrounds are backdrops: keep them dark.
            if prop == "background-color" and int(shade) >= 800 and shade in original_slate:
                changed = True
                return original_slate[shade]
            return match.group(0)
        if prop == "color" and shade in TEXT_SHADE:
            changed = True
            return f"var(--color-{hue}-{TEXT_SHADE[shade]})"
        if prop == "background-color" and shade in BG_TINT:
            changed = True
            return f"color-mix(in oklab,var(--color-{hue}-500) {BG_TINT[shade]}%,transparent)"
        if prop.startswith("border") and prop.endswith("color") and shade in BORDER_TINT:
            changed = True
            return f"color-mix(in oklab,var(--color-{hue}-500) {BORDER_TINT[shade]}%,transparent)"
        return match.group(0)

    new = COLOR_VAR.sub(swap, value)
    return new if changed else None


def generate(source):
    """dark.css, as text, for the compiled stylesheet `source`."""
    original_slate = dict(SLATE_VALUE.findall(source))
    out = [
        "/* Generated by `manage.py build_dark_css` from app.css - do not edit. */",
        f"{SCOPE}{{color-scheme:dark;--lgmed-surface:{SURFACE};"
        + "".join(f"--color-slate-{k}:{v};" for k, v in SLATE.items())
        + "}",
    ]
    seen = set()
    for selector, body in RULE.findall(source):
        selector = selector.strip()
        if not selector.startswith(".") or selector in seen:
            continue
        declarations = []
        for declaration in body.split(";"):
            prop, _, value = declaration.partition(":")
            new = convert(prop.strip(), value.strip(), original_slate)
            if new is not None:
                declarations.append(f"{prop.strip()}:{new}")
        if declarations:
            seen.add(selector)
            scoped = ",".join(f"{SCOPE} {part.strip()}" for part in selector.split(","))
            out.append(f"{scoped}{{{';'.join(declarations)}}}")
    return "\n".join(out) + "\n"


class Command(BaseCommand):
    help = "Generate static/css/dark.css from the compiled static/css/app.css."

    def handle(self, *args, **options):
        css_dir = Path(settings.BASE_DIR) / "static" / "css"
        output = generate((css_dir / "app.css").read_text(encoding="utf-8"))
        (css_dir / "dark.css").write_text(output, encoding="utf-8")
        self.stdout.write(f"Wrote static/css/dark.css ({output.count(chr(10)) - 2} rules).")
